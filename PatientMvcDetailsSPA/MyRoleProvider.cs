        public override string[] GetRolesForUser(string username)
        {
            using (PatientDbContext db = new PatientDbContext())
            {
                var roles = (from user in db.tbl_Users
                             join userRole in db.tbl_UserRoles on user.UserId equals userRole.UserId
                             join role in db.tbl_Roles on userRole.RoleId equals role.RoleId
                             where user.UserName == username
                             select role.RoleName).ToArray();
                return roles;
            }
        }

